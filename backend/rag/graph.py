def route_question(state):
    """
    Determine which data source should be used to answer the
    user's question.

    The routing LLM decides whether the question should be handled
    using the vector store (RAG) or an external web search.

    If the routing model does not return a valid tool call, the
    question is routed to the fallback LLM.

    Args:
        state (GraphState):
            Current state of the LangGraph workflow containing
            the user's question.

    Returns:
        str:
            Name of the next LangGraph node to execute.
            Possible values are:
                - "llm_fallback"
                - "web_search"
                - "vectorstore"
    """
    print("---Routing question...---")
    question = state["question"]
    source = route_question_chain().invoke({"question": question})

    if "tool_calls" not in source.additional_kwargs:
        print("---Route question to fallback---")
        return "llm_fallback"
    if len(source.additional_kwargs["tool_calls"]) == 0:
        raise "Route could no decide source"

    datasource = source.additional_kwargs["tool_calls"][0]["function"]["name"]
    if datasource == "web_search":
        print("---Route question to web search---")
        return "web_search"
    elif datasource == "vectorstore":
        print("---Route question to RAG---")
        return "vectorstore"
    else:
        print('f{datasource}: Route undefined, route to web search---')
        return "web_search"



def decide_to_generate(state):
    """
    Decide whether the system should generate an answer using
    the retrieved documents or perform a web search.

    This function is used after document relevance grading.
    If at least one relevant document remains, the workflow
    proceeds to answer generation. Otherwise, it searches the web
    for additional information.

    Args:
        state (GraphState):
            Current state containing the filtered documents.

    Returns:
        str:
            Name of the next LangGraph node:
                - "generate" if relevant documents exist.
                - "web_search" if no relevant documents exist.
    """
    print("---Decide to generate---")
    filtered_documents = state["documents"]

    if not filtered_documents:
        print("---No related document, do web search---")
        return "web_search"
    else:

        print("---Document related, generate---")
        return "generate"


def check_hallucination_and_utility(state):
    """
    Evaluate whether the generated answer is both grounded in
    the retrieved documents and useful for answering the question.

    The function performs two checks:

        1. Hallucination check:
           Determines whether the generated answer is supported
           by the retrieved documents.

        2. Utility check:
           Determines whether the generated answer actually
           addresses the user's question.

    The result determines whether the answer should be accepted,
    regenerated, or followed by another web search.

    Args:
        state (GraphState):
            Current state containing the question, retrieved
            documents, and generated answer.

    Returns:
        str:
            Routing decision for the next LangGraph node:
                - "useful" if the answer is grounded and answers
                  the question.
                - "not useful" if the answer is grounded but does
                  not adequately answer the question.
                - "not supported" if the answer is not grounded
                  in the retrieved documents.
    """
    print("---Check hallucination and utility---")
    question = state["question"]
    document = state["documents"]
    generation = state["generation"]

    check_hallucination = hallucination_grader().invoke({"document": document, "generation": generation})
    is_grounded = check_hallucination.is_grounded

    if is_grounded == "yes":
        print("---Generation is grounded---")
        print("---Check utility---")
        check_utility = answer_grader().invoke({"question": question, "generation": generation})
        has_answered = check_utility.has_answered
        if has_answered == "yes":
            print("---Generation addresses question---")
            return "useful"
        else:
            print("---Generation not useful, web search again---")
            return "not useful"
    else:
        print("---Generation is not grounded in documents, regeneration---")
        return "not supported"


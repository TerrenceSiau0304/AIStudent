from typing import List
from typing_extensions import TypedDict
from langchain_core.documents import Document
from langgraph.graph import END, StateGraph, START



from rag.rag_fusion import retrieval_rag_fusion
from rag.fallback import fallback
from rag.generation import generate_chain
from rag.graders import retrieval_grader, answer_grader, hallucination_grader
from rag.web_search import web_search_tool
from rag.routing import route_question_chain
from core.config import DATA_DIR


class GraphState(TypedDict):
    """
    Represents the shared state of the StudentAI LangGraph workflow.

    The graph state is passed between nodes during graph execution.
    Each node can read values from the state and update the relevant
    fields as the question moves through the retrieval, grading,
    generation, and fallback stages.

    Attributes:
        question (str):
            The original question submitted by the user.

        generation (str):
            The answer generated by the language model.

        documents (List[str]):
            A list of documents retrieved from the vector store
            and used as context for generating the answer.
    """
    '''
    Graph State
    '''
    question: str
    generation: str
    documents: List[str]

"""
====================================================
Nodes
"""


def make_retrieve_node(retriever):
    retrieval_chain = retrieval_rag_fusion(retriever)  

    def retrieve(state):
        """
        Retrieve relevant documents for the user's question.

        Args:
            state (GraphState):
                Current state of the LangGraph workflow.

        Returns:
            dict:
                Updated graph state containing the retrieved
                documents and original question.
        """
        print("---Retrieving...---")
        question = state["question"]
        documents = retrieval_chain.invoke({"question": question})
        return {"documents": documents, "question": question}

    return retrieve

def llm_fallback(state):
    """
    Generate an answer using the fallback language model.

    This node is used when the primary RAG workflow cannot
    provide a suitable answer. Instead of relying on retrieved
    documents, the fallback model answers using its general
    knowledge.

    Args:
        state (GraphState):
            Current state of the LangGraph workflow.

    Returns:
        dict:
            Updated graph state containing the generated answer
            and original question.
    """
    print("---Fallback...---")
    question = state["question"]
    generation = fallback().invoke({"question": question})
    return {"question": question, "generation": generation}

def generate(state):
    """
    Generate an answer using the retrieved documents.

    This node performs the main RAG generation step. It provides
    the user's question and retrieved documents to the generation
    chain so that the language model can produce a
    document-grounded answer.

    Args:
        state (GraphState):
            Current state containing the user's question and
            retrieved documents.

    Returns:
        dict:
            Updated graph state containing the generated answer,
            question, and retrieved documents.
    """
    print("---Generating...---")
    question = state["question"]
    documents = state["documents"]
    if not isinstance(documents, list):
        documents = [documents]
        
    generated_output = generate_chain().invoke({"question": question, "documents": documents})
    return {"question": question, "generation": generated_output, "documents": documents}


def grade_documents(state):
    """
    Evaluate the relevance of retrieved documents.

    Each retrieved document is passed through the retrieval
    grader to determine whether it is relevant to the user's
    question.

    Documents graded as relevant are retained, while irrelevant
    documents are removed from the graph state.

    Args:
        state (GraphState):
            Current state containing the user's question and
            retrieved documents.

    Returns:
        dict:
            Updated graph state containing only relevant documents
            and the original question.
    """
    print("---Checking document relevance...---")
    question = state["question"]
    documents = state["documents"]

    if not isinstance(documents, list):
        documents = [documents]

    filtered_docs = []
    for d in documents:
        score = retrieval_grader().invoke({"question": question, "document": d})
        grade = score.is_relevant
        if grade == "yes":
            print("---GRADE: Document relevant---")
            filtered_docs.append(d)
        else:
            print("---GRADE: Document not relevant---")
            continue
    return {"documents": filtered_docs, "question": question}

def web_search(state):
    """
    Search the web for additional information about the user's
    question.

    This node is used when the retrieved documents are insufficient
    or when the graph determines that external information is
    required.

    The web search results are converted into LangChain Document
    objects so they can be processed in the same way as documents
    retrieved from the vector store.

    Args:
        state (GraphState):
            Current state containing the user's question.

    Returns:
        dict:
            Updated graph state containing web search documents
            and the original question.
    """

    print("---Web Searching...---")
    question = state["question"]

    docs = web_search_tool.invoke({"query": question}) 
    web_search_doc = []
    for d in docs["results"]:
        doc = Document(page_content=str(d["content"]),
                        metadata={
                            "source":d["url"]
                        })
        web_search_doc.append(doc)
        
    return { "documents": web_search_doc, "question": question}



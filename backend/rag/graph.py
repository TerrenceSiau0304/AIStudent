def build_graph(retriever, checkpointer):
    """
    Build and compile the StudentAI LangGraph workflow.

    This function defines the graph structure by registering all
    processing nodes, connecting them with normal edges, and
    defining conditional edges that determine the next step based
    on the current graph state.

    The workflow supports:

        1. Question routing
        2. Vector store retrieval
        3. Document relevance grading
        4. Web search fallback
        5. Answer generation
        6. Hallucination checking
        7. Answer utility checking
        8. LLM fallback
        9. Conversation state persistence through a checkpointer

    Args:
        retriever:
            Retriever used by the vector store retrieval node
            to search for relevant documents.

        checkpointer:
            LangGraph checkpointer used to persist graph state
            between requests and conversation sessions.

    Returns:
        CompiledStateGraph:
            A compiled LangGraph workflow ready to process
            user questions.
    """
    workflow = StateGraph(GraphState)
    workflow.add_node("web_search", web_search)
    retrival_node = make_retrieve_node(retriever)
    workflow.add_node("retrieve", retrival_node)
    workflow.add_node("grade_document", grade_documents)
    workflow.add_node("generate", generate)
    workflow.add_node("llm_fallback", llm_fallback)

    workflow.add_conditional_edges(
        START, 
        route_question,
        {
            "web_search": "web_search",
            "vectorstore": "retrieve",
            "llm_fallback": "llm_fallback",
        },
    )

    workflow.add_edge("web_search", "grade_document")
    workflow.add_edge("retrieve", "grade_document")
    workflow.add_edge("llm_fallback", END)

    workflow.add_conditional_edges(
        "grade_document",
        decide_to_generate,
        {
            "web_search": "web_search",
            "generate": "generate",
        },
    )

    workflow.add_conditional_edges(
        "generate",
        check_hallucination_and_utility,
        {
            "useful": END,
            "not useful": "web_search",
            "not supported": "generate",
        },
    )

 
    return workflow.compile(checkpointer=checkpointer)


    

